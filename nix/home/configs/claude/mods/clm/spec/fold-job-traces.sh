#!/bin/sh
# Regenerate: nice -n 15 sh nix/home/configs/claude/mods/clm/spec/fold-job-traces.sh
#
# Samples random runs of the `current` instance of fold-job.qnt as ITF traces and bundles each state's model variables,
# the action that produced it and its nondet picks into fold-job-traces.ts for hooks/fold-conformance.test.ts (the
# plugin test loader imports code files only). SEED and TRACES are the values whose coverage that test asserts.
set -eu
SEED=${SEED:-0x2a}
TRACES=${TRACES:-80}
STEPS=${STEPS:-30}
here=$(cd "$(dirname "$0")" && pwd)
out=$(mktemp -d)
trap 'rm -rf -- "${out:?}"' EXIT
quint run "$here/fold-job.qnt" --main current --mbt --out-itf "$out/t_{seq}.itf.json" \
  --n-traces "$TRACES" --max-samples "$TRACES" --max-steps "$STEPS" --seed "$SEED" >/dev/null
{
  printf '// Generated by spec/fold-job-traces.sh (SEED=%s TRACES=%s STEPS=%s) from spec/fold-job.qnt; do not edit.\n' "$SEED" "$TRACES" "$STEPS"
  cat <<'EOF'
export type Msg = { typed: boolean; inStore: boolean; inContext: boolean; handled: boolean; carried: number; engine: boolean; foldedRow: boolean; retired: boolean; left: boolean }
export type Job = { phase: string; attempt: number; fits: boolean; snap: number[]; csnap: number[]; mechanical: boolean }
// a: the action that produced this state, p: its nondet picks, then the model variables after it.
export type State = { a: string; p: Record<string, unknown>; m: Record<string, Msg>; j: Job; w: boolean; s: { active: boolean; pc: number; dropped: number[] } }
// Packed to keep the file small: a Msg is its true flags (t s c h e f r l) followed by carried, booleans are 0 or 1.
// reinjected is not packed: noReinjection holds on current, so it is false in every state.
type Packed = [string, Record<string, unknown>, string, string, [string, number, number, number[], number[], number], number, [number, number, number[]]]
const msg = (f: string): Msg => ({
  typed: f.includes('t'), inStore: f.includes('s'), inContext: f.includes('c'), handled: f.includes('h'), engine: f.includes('e'), foldedRow: f.includes('f'), retired: f.includes('r'), left: f.includes('l'), carried: Number(f.replace(/[a-z]/g, '')),
})
const unpack = ([a, p, m1, m2, [phase, attempt, fits, snap, csnap, mechanical], w, [active, pc, dropped]]: Packed): State => ({
  a, p, m: { 1: msg(m1), 2: msg(m2) }, j: { phase, attempt, fits: fits === 1, snap, csnap, mechanical: mechanical === 1 }, w: w === 1, s: { active: active === 1, pc, dropped },
})
EOF
  printf 'const packed: Packed[][] = '
  ls "$out"/t_*.itf.json | sort -V | xargs jq -c '
    def n: if type == "object" and has("#bigint") then (.["#bigint"] | tonumber)
      elif type == "object" and has("#set") then [.["#set"][] | n] else . end;
    def b: if . then 1 else 0 end;
    def flag($k; $c): if .[$k] then $c else "" end;
    def msg: map_values(n) | flag("typed"; "t") + flag("inStore"; "s") + flag("inContext"; "c") + flag("handled"; "h") + flag("engine"; "e") + flag("foldedRow"; "f") + flag("retired"; "r") + flag("left"; "l") + (.carried | tostring);
    [.states[] |
      (.["current::foldJob::msgs"]["#map"] | map({key: (.[0] | n | tostring), value: (.[1] | msg)}) | from_entries) as $m |
      (.["current::foldJob::job"] | map_values(n)) as $j |
      (.["current::foldJob::swap"] | map_values(n)) as $s |
      [ .["mbt::actionTaken"],
        (.["mbt::nondetPicks"] | with_entries(select(.value.tag == "Some") | .value = (.value.value | n))),
        $m["1"], $m["2"],
        [$j.phase, $j.attempt, ($j.fits | b), $j.snap, $j.csnap, ($j.mechanical | b)],
        (.["current::foldJob::compactWaiting"] | b),
        [($s.active | b), $s.pc, $s.dropped] ]]' | jq -s -c .
  printf 'export const traces: State[][] = packed.map(trace => trace.map(unpack))\n'
} > "$here/fold-job-traces.ts"
